// N4 → N2 syllabus outline. Each day lists its planned points; days become
// playable when their full content (words, kanji, grammar, reading, listening,
// speaking) is written in a level file and registered in LEVEL_CONTENT.
// Every unit ends with an automatic review day.

export type Level = 'N5' | 'N4' | 'N3' | 'N2';

export interface OutlineDay {
  slug: string;
  title: string;
  titleJa: string;
  points: string[];
}

export interface OutlineUnit {
  level: Level;
  title: string;
  titleJa: string;
  days: OutlineDay[];
}

let counter: Record<string, number> = {};
const unit = (level: Level, title: string, titleJa: string, days: [string, string, string][]): OutlineUnit => ({
  level,
  title,
  titleJa,
  days: days.map(([t, tj, points]) => {
    counter[level] = (counter[level] ?? 0) + 1;
    return { slug: `${level.toLowerCase()}-${String(counter[level]).padStart(3, '0')}`, title: t, titleJa: tj, points: points.split(' · ') };
  }),
});

